package dev.iskandern.kotin.landxml

/**
 * Шкала подписей, которые строит сам просмотрщик (LandXML): все — постоянного экранного размера в dp, JetBrains Mono,
 * тёмные с белым ореолом, прореживаются вместе («Прореживать подписи по масштабу»). Кегли — только здесь.
 * Текст DXF (TEXT, MTEXT, ATTRIB, размеры) — геометрия чертежа с высотой в его единицах и сюда не относится.
 */
object LabelScale {
  /** Значения: по пикетам (скорость, интенсивность…), вершины углов, колодцы и трубы, поперечники. */
  const val TEXT_DP = 12.0

  /** Номер и отметка точки (CgPoint, Monument, станции съёмки) — две строки у значка. */
  const val POINT_DP = 11.0

  /** Пикеты «ПК3» — полужирным (эталон T12). */
  const val STATION_DP = 13.0

  /**
   * Заголовки объектов: участки (Parcel), ситуация (PlanFeature) — полужирным; имя трассы — курсивом. Тот же кегль,
   * что у пикетов: лестница 11 / 12 / 13 / 13 — два шага читаются как иерархия, три — как разнобой (решение владельца 20.10.2026).
   */
  const val TITLE_DP = 13.0

  /** Подпись у значка — на столько правее его центра, dp (у точек — так же). */
  const val MARK_SHIFT_DP = 8.0

  // высота заглавных JetBrains Mono — доля кегля (как FACE_CAP_HEIGHT[FACE_MONO*] в атласе; landxml собирается и в
  // воркер web, без scene)
  const val MONO_CAP_HEIGHT = 0.73

  /** Высота подписи кегля [fontDp]: отрицательная — dp на экране, по заглавным ([SceneLabel.height][dev.iskandern.kotin.model.SceneLabel]). */
  fun height(fontDp: Double): Double = -fontDp * MONO_CAP_HEIGHT
}
